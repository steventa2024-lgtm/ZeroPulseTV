# Builds the ZeroPulse TV APK with the bare Android SDK tools (aapt2, javac, d8, zipalign, apksigner).
# No Gradle, no third-party libraries. See docs/BUILDING.md.
#
# Usage:
#   powershell -ExecutionPolicy Bypass -File launcher\build.ps1 -Keystore C:\path\my-release.jks [-Tools ..\tools]
#                                                               [-OutApk out.apk] [-Commit label]
#   Keystore password: $env:ZP_KEYSTORE_PASS (used for both the keystore and the key).
#
# -Tools must contain:  jdk\ (JDK 17)  and  sdk\build-tools\android-14\ (Build-Tools 34) and
#                       sdk\platforms\android-34\android.jar
#
# A build signed with your own key installs on a TV that does not have ZeroPulse TV yet, but it cannot
# update an installation of the official release: Android only accepts updates signed with the same key.
param(
    [string]$Keystore = "",
    [string]$Tools = (Join-Path $PSScriptRoot "..\tools"),
    [string]$OutApk = (Join-Path $PSScriptRoot "ZeroPulseTV.apk"),
    # Label for the About screen; defaults to the git commit of this checkout
    [string]$Commit = ""
)
$ErrorActionPreference = "Stop"
$src   = $PSScriptRoot
$tools = (Resolve-Path $Tools).Path
$env:JAVA_HOME = Join-Path $tools "jdk"
$env:PATH = "$env:JAVA_HOME\bin;$env:PATH"
$bt  = Join-Path $tools "sdk\build-tools\android-14"
$jar = Join-Path $tools "sdk\platforms\android-34\android.jar"
$out = Join-Path $src "build"
foreach ($need in @("$env:JAVA_HOME\bin\javac.exe", "$bt\aapt2.exe", "$bt\d8.bat", "$bt\apksigner.bat", $jar)) {
    if (-not (Test-Path $need)) { throw "Missing $need - see docs/BUILDING.md for the toolchain layout." }
}
if (-not $Keystore -or -not (Test-Path $Keystore)) { throw "Pass -Keystore <your release keystore>. See docs/BUILDING.md." }
if (-not $env:ZP_KEYSTORE_PASS) { throw "Set ZP_KEYSTORE_PASS to the keystore password." }

# Plain string-array splatting: avoids PowerShell's special handling of "-name:value" arguments.
function Run([string]$exe, [string[]]$a) {
    & $exe @a
    if ($LASTEXITCODE -ne 0) { throw "$exe failed ($LASTEXITCODE)" }
}

if (Test-Path $out) { Remove-Item -Recurse -Force $out }
New-Item -ItemType Directory -Force "$out\classes" | Out-Null

"== aapt2 compile + link (manifest + resources)"
Run "$bt\aapt2.exe" @("compile", "--dir", "$src\res", "-o", "$out\res.zip")
# Assets are added with jar below: aapt2 -A on Windows stores paths with backslashes, which Android can't open.
Run "$bt\aapt2.exe" @("link", "-o", "$out\base.apk", "-I", $jar, "--manifest", "$src\AndroidManifest.xml",
    "--min-sdk-version", "26", "--target-sdk-version", "31", "$out\res.zip", "--java", "$out\gen", "--auto-add-overlay")

"== javac"
$java = @(Get-ChildItem "$src\src" -Recurse -Filter *.java | ForEach-Object FullName)
if (-not $Commit) {
    $Commit = (& git -C $src rev-parse --short HEAD 2>$null)
    if (-not $Commit) { $Commit = "unknown" } elseif (& git -C $src status --porcelain 2>$null) { $Commit += "-modified" }
}
$stamp = Get-Date -Format "yyyyMMdd.HHmm"
New-Item -ItemType Directory -Force "$out\gen\tv\calmhome\launcher" | Out-Null
[IO.File]::WriteAllText("$out\gen\tv\calmhome\launcher\BuildInfo.java",
    "package tv.calmhome.launcher;`n/** Generated by build.ps1. */`npublic final class BuildInfo {`n" +
    "    public static final String BUILD = `"$stamp`";`n    public static final String COMMIT = `"$Commit`";`n" +
    "    private BuildInfo() { }`n}`n")
$java += @(Get-ChildItem "$out\gen" -Recurse -Filter *.java | ForEach-Object FullName)
Run javac (@("-nowarn", "-Xlint:-options", "-source", "8", "-target", "8", "-bootclasspath", "$jar;$bt\core-lambda-stubs.jar",
    "-encoding", "UTF-8", "-d", "$out\classes") + $java)

"== d8"
Run jar @("--create", "--file", "$out\classes.jar", "-C", "$out\classes", ".")
Run "$bt\d8.bat" @("--release", "--min-api", "26", "--lib", $jar, "--output", $out, "$out\classes.jar")

"== package"
Push-Location $out
Run jar @("--update", "--no-manifest", "--file", "base.apk", "classes.dex")
Pop-Location
Run jar @("--update", "--no-manifest", "--no-compress", "--file", "$out\base.apk", "-C", $src, "assets")
Run "$bt\zipalign.exe" @("-p", "-f", "4", "$out\base.apk", "$out\aligned.apk")

"== sign"
Run "$bt\apksigner.bat" @("sign", "--ks", $Keystore, "--ks-pass", "env:ZP_KEYSTORE_PASS", "--key-pass", "env:ZP_KEYSTORE_PASS",
    "--out", $OutApk, "$out\aligned.apk")
Run "$bt\apksigner.bat" @("verify", "--print-certs", $OutApk)
"Built {0} ({1:N0} KB)" -f $OutApk, ((Get-Item $OutApk).Length / 1KB)
